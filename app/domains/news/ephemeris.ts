export function saintOf(day: DateTime): string {
  return SAINTS[day.month - 1]?.[day.day - 1] ?? ''
}

export function quoteOf(day: DateTime): { text: string; author: string } {
  return QUOTES[(day.ordinal - 1) % QUOTES.length]
}
